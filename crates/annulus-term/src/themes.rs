/// The theme called `name`, or `None` for a name this version does not know.
#[must_use]
pub fn theme(name: &str) -> Option<Palette> {
    Some(match name {
        "Annulus Dark" => Palette::annulus_dark(),
        "Annulus Light" => Palette::annulus_light(),
        "Solarized Dark" => scheme(
            SOLARIZED,
            [0x83, 0x94, 0x96],
            [0x00, 0x2B, 0x36],
            [0x93, 0xA1, 0xA1],
            [0x07, 0x36, 0x42],
        ),
        "Solarized Light" => scheme(
            SOLARIZED,
            // base01, Solarized's emphasized text: base00 (its body text) is 4.1:1 here.
            [0x58, 0x6E, 0x75],
            [0xFD, 0xF6, 0xE3],
            [0x58, 0x6E, 0x75],
            [0xEE, 0xE8, 0xD5],
        ),
        "Dracula" => scheme(
            DRACULA,
            [0xF8, 0xF8, 0xF2],
            [0x28, 0x2A, 0x36],
            [0xF8, 0xF8, 0xF2],
            [0x44, 0x47, 0x5A],
        ),
        "Nord" => scheme(
            NORD,
            [0xD8, 0xDE, 0xE9],
            [0x2E, 0x34, 0x40],
            [0xD8, 0xDE, 0xE9],
            [0x43, 0x4C, 0x5E],
        ),
        "Gruvbox Dark" => scheme(
            GRUVBOX_DARK,
            [0xEB, 0xDB, 0xB2],
            [0x28, 0x28, 0x28],
            [0xEB, 0xDB, 0xB2],
            [0x50, 0x49, 0x45],
        ),
        "Gruvbox Light" => scheme(
            GRUVBOX_LIGHT,
            [0x3C, 0x38, 0x36],
            [0xFB, 0xF1, 0xC7],
            [0x3C, 0x38, 0x36],
            [0xD5, 0xC4, 0xA1],
        ),
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// WCAG relative luminance contrast between two colors.
    fn contrast(a: Rgb, b: Rgb) -> f64 {
        let luminance = |c: Rgb| {
            let channel = |v: u8| {
                let v = f64::from(v) / 255.0;
                if v <= 0.039_28 {
                    v / 12.92
                } else {
                    ((v + 0.055) / 1.055).powf(2.4)
                }
            };
            0.2126 * channel(c.r) + 0.7152 * channel(c.g) + 0.0722 * channel(c.b)
        };
        let (x, y) = (luminance(a), luminance(b));
        (x.max(y) + 0.05) / (x.min(y) + 0.05)
    }

    #[test]
    fn every_listed_theme_exists_and_its_text_is_readable() {
        for name in THEMES {
            let palette = theme(name).unwrap_or_else(|| panic!("{name} is listed but missing"));
            let ratio = contrast(palette.foreground, palette.background);
            assert!(
                ratio >= 4.5,
                "{name}: text contrast {ratio:.2} is below 4.5"
            );
        }
        assert_eq!(theme("No Such Theme"), None);
        assert_eq!(theme(THEMES[0]), Some(Palette::annulus_dark()));
    }
}

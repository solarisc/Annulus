/// `[r, g, b]` as a color.
const fn hex([r, g, b]: [u8; 3]) -> Rgb {
    Rgb { r, g, b }
}

fn scheme(
    ansi: [[u8; 3]; 16],
    foreground: [u8; 3],
    background: [u8; 3],
    cursor: [u8; 3],
    selection: [u8; 3],
) -> Palette {
    Palette {
        ansi: ansi.map(hex),
        foreground: hex(foreground),
        background: hex(background),
        cursor: hex(cursor),
        selection: hex(selection),
    }
}

